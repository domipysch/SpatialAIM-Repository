"""
Report cards: a figure with its export popover, the two-per-row card grid with
each card's "?" help dialog, and the metrics table.
"""

from __future__ import annotations

from typing import Callable, NamedTuple

import pandas as pd
import streamlit as st

from spatialaim.gui.render.common import figure_to_bytes
from spatialaim.gui.widgets.linked_plot import linked_plot

_EXPORT_MIME = {
    "png": "image/png",
    "svg": "image/svg+xml",
    "pdf": "application/pdf",
}


def export_popover(fig, *, key: str, stem: str) -> None:
    """A small ⬇ popover under a figure: pick a format, render it server-side
    (kaleido), and download. Kept on-demand — the image is only built when the
    user clicks *Generate*, so the (heavy) kaleido call never runs on a plain
    rerun.

    The generated bytes are cached in ``session_state`` under ``stem`` (not the
    widget ``key``): ``stem`` encodes the figure's identity — K, threshold, etc. —
    so moving the K slider (or the threshold) invalidates the cache instead of
    serving the previous figure's image under a new filename."""
    store = stem  # figure-identity token; changes whenever the figure changes
    with st.popover("⬇ Export"):
        fmt = st.radio(
            "Format",
            list(_EXPORT_MIME),
            horizontal=True,
            key=f"{key}_fmt",
            help="PNG is always faithful; the UMAP/spatial scatter panels "
            "rasterise inside SVG/PDF (WebGL), while bar/box/line/heatmap "
            "figures stay true vector.",
        )
        if st.button("Generate", key=f"{key}_gen", width="stretch"):
            st.session_state.pop(f"{store}_err", None)
            try:
                st.session_state[f"{store}_bytes"] = figure_to_bytes(fig, fmt)
                st.session_state[f"{store}_ext"] = fmt
            except Exception as exc:  # noqa: BLE001 - surfaced below
                st.session_state.pop(f"{store}_bytes", None)
                st.session_state[f"{store}_err"] = str(exc)

        data = st.session_state.get(f"{store}_bytes")
        if data is not None:
            ext = st.session_state.get(f"{store}_ext", "png")
            st.download_button(
                f"Download .{ext}",
                data,
                file_name=f"{stem}.{ext}",
                mime=_EXPORT_MIME.get(ext, "application/octet-stream"),
                key=f"{key}_dl",
                width="stretch",
            )
        if st.session_state.get(f"{store}_err"):
            st.error(st.session_state[f"{store}_err"])


def plot_card(
    fig,
    *,
    key: str,
    stem: str,
    caption: str | None = None,
    link_group: str | None = None,
    on_pick=None,
) -> None:
    """Render a Plotly figure as a report card: the chart, an optional caption,
    and an export popover beneath it.

    With ``link_group`` the chart is drawn by ``linked_plot`` instead of
    ``st.plotly_chart``, so every card in that group highlights the same K on
    hover and reports clicks through ``on_pick``.
    """
    if link_group is None:
        st.plotly_chart(fig, width="stretch", key=key)
    else:
        linked_plot(fig, key=key, group=link_group, on_pick=on_pick)
    if caption:
        st.caption(caption)
    export_popover(fig, key=f"{key}_exp", stem=stem)


class Card(NamedTuple):
    """One report card: a bold title, the body that draws it, and optionally the
    explanation behind the card's ``?``. Cards without ``help`` get no ``?``."""

    title: str
    body: Callable[[], None]
    help: str | None = None
    # Distinguishes the ``?`` buttons of two cards that share a title (a mapper
    # tab and the Compare tab render the same grid function).
    key: str = ""
    # A wide card takes a whole row of the grid instead of half of one.
    wide: bool = False


@st.dialog("About this card", width="large")
def _card_help_dialog() -> None:
    """Modal explaining one report card.

    One dialog serves every card, reading which one from session state. An open
    dialog is re-run by Streamlit as a stored fragment, so the decorator stays at
    module level and the card's own title goes in the body — decorating per call
    to get a dynamic dialog title would make that stored fragment a function
    object rebuilt on every run.
    """
    title = st.session_state.get("_card_help_title", "")
    if title:
        st.markdown(f"**{title}**")
    st.markdown(st.session_state.get("_card_help_text", ""))
    if st.button("Close", key="card_help_close"):
        st.rerun()


def render_card_grid(cards: list[Card]) -> None:
    """Lay out cards two per row, each in a bordered container.

    The header is one distributed flex row, not two columns: a column keeps its
    share of the width whatever it holds, so the ``?`` ended up left-aligned
    inside its own column with dead space to its right. ``distribute`` pushes the
    first and last element to the two edges instead, so the icon sits flush in
    the card's top-right corner. A ``wide`` card gets a row of its own.
    """
    rows: list[list[Card]] = []
    for card in cards:
        if card.wide or not rows or len(rows[-1]) == 2 or rows[-1][0].wide:
            rows.append([card])
        else:
            rows[-1].append(card)
    for row in rows:
        cols = [st.container()] if row[0].wide else st.columns(2)
        for col, card in zip(cols, row):
            with col, st.container(border=True):
                hdr = st.container(
                    horizontal=True,
                    horizontal_alignment="distribute",
                    vertical_alignment="center",
                )
                hdr.markdown(f"**{card.title}**")
                if card.help:
                    if hdr.button(
                        "",
                        icon=":material/help:",
                        type="tertiary",
                        key=f"cardhelp_{card.key or card.title}",
                        help="What is shown here?",
                    ):
                        st.session_state["_card_help_title"] = card.title
                        st.session_state["_card_help_text"] = card.help
                        _card_help_dialog()
                card.body()


def render_metrics(container, d: dict, level: int = 0) -> None:
    """Show a metrics dict: scalars as a two-column table, nested dicts recursively."""
    scalars = {k: v for k, v in d.items() if not isinstance(v, (dict, list))}
    if scalars:
        df = pd.DataFrame(
            {"metric": list(scalars.keys()), "value": list(scalars.values())}
        )
        container.dataframe(df, hide_index=True, width="stretch")
    for k, v in d.items():
        if isinstance(v, dict):
            container.markdown(f"{'#' * min(6, 4 + level)} {k}")
            render_metrics(container, v, level + 1)
        elif isinstance(v, list):
            try:
                container.dataframe(pd.DataFrame(v), width="stretch")
            except Exception:  # noqa: BLE001
                container.write({k: v})
